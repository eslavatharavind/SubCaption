export function getFontById(id: string): FontMetadata | undefined {
  return FONT_REGISTRY.find((f) => f.id === id || f.family.toLowerCase() === id.toLowerCase());
}

export function getFontsByCategory(category: string): FontMetadata[] {
  if (category === 'All') return FONT_REGISTRY;
  return FONT_REGISTRY.filter((f) => f.category === category);
}
